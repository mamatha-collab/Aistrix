import {test,expect} from '@playwright/test'

async function openPrimary(page, label, isMobile) {
  if (isMobile) await page.getByRole('button',{name:'Toggle menu'}).click()
  const nav=isMobile?page.locator('aside'):page.getByRole('navigation',{name:'Business sections'})
  await nav.getByRole('button',{name:new RegExp(`^${label}\\b`)}).click()
}

test('client workspace shows published apps and saves favorites',async({page,isMobile},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/e2e/fixtures/?scenario=business')
  await page.evaluate(async()=>{const {applyTheme}=await import('/src/utils/theme.js');applyTheme('light')})
  await expect(page.getByRole('heading',{name:'Market',exact:true})).toBeVisible()
  await expect(page.locator('main').getByText('Fixture Assistant',{exact:true})).toBeVisible()
  await expect(page.getByText('Second Assistant',{exact:true})).toHaveCount(0)
  await expect(page.getByText('Build AI App',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Save Fixture Assistant',exact:true}).click()
  await expect(page.getByRole('button',{name:'Saved Fixture Assistant',exact:true})).toBeDisabled()
  await openPrimary(page,'My apps',isMobile)
  await expect(page.getByRole('heading',{name:'My apps',exact:true})).toBeVisible()
  await expect(page.locator('main').getByRole('button',{name:/Discover/})).toHaveCount(0)
  await expect(page.locator('main').getByText('Fixture Assistant',{exact:true})).toBeVisible()
  await page.getByRole('searchbox',{name:'Search apps',exact:true}).fill('No matching app')
  await expect(page.locator('main').getByText('Fixture Assistant',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Clear search'}).click()
  await expect(page.locator('main').getByText('Fixture Assistant',{exact:true})).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('business-apps-light.png')})
  await page.getByRole('button',{name:'Open app',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Opened Fixture Assistant')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('client navigation, account dismissal and workflow search work',async({page,isMobile},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/e2e/fixtures/?scenario=business')
  await openPrimary(page,'Workflows',isMobile)
  await expect(page.getByRole('heading',{name:'Keep your work moving'})).toBeVisible()
  await page.getByRole('searchbox',{name:'Search workflows',exact:true}).fill('Invoice')
  await page.getByRole('button',{name:'Account menu'}).click()
  await expect(page.getByRole('menuitem',{name:'Account settings'})).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('menu')).toHaveCount(0)
  await page.getByRole('button',{name:'Account menu'}).click()
  await page.getByRole('menuitem',{name:'Change theme'}).click()
  await page.screenshot({path:testInfo.outputPath('business-workflows.png')})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('Market highlights the catalog with discovery controls and settings in the side pane',async({page,isMobile},testInfo)=>{
  await page.goto('/e2e/fixtures/?scenario=business')
  await expect(page.getByRole('heading',{name:'Market',exact:true})).toBeVisible()
  const toolbar=page.getByRole('region',{name:'Market discovery'})
  await expect(toolbar.getByRole('searchbox',{name:'Search apps by title'})).toBeVisible()
  await expect(page.getByText('Find the right app for your work')).toHaveCount(0)
  if (!isMobile) {
    const row=await page.locator('[data-frame-nav]').boundingBox()
    const search=await toolbar.getByRole('searchbox').boundingBox()
    expect(row.height).toBe(93)
    expect(search.y).toBeGreaterThanOrEqual(row.y)
    expect(search.y+search.height).toBeLessThanOrEqual(row.y+row.height)
    await expect(page.getByRole('navigation',{name:'Business sections'}).getByRole('button',{name:'Marketplace',exact:true})).toHaveAttribute('aria-current','page')
  }
  await toolbar.getByLabel('Price filter').selectOption('paid')
  await expect(page.getByText('0 apps available',{exact:true})).toBeVisible()
  await toolbar.getByLabel('Price filter').selectOption('all')
  const groups=toolbar.getByRole('navigation',{name:'App groups'})
  await expect(toolbar.getByRole('combobox',{name:'App group',exact:true})).toHaveCount(0)
  await expect(toolbar.getByRole('navigation',{name:'App types'})).toHaveCount(0)
  await groups.getByRole('button',{name:'Other',exact:true}).click()
  await expect(page.getByText('0 apps available',{exact:true})).toBeVisible()
  await groups.getByRole('button',{name:'All apps',exact:true}).click()
  await expect(page.getByRole('button',{name:'Fixture Assistant',exact:true})).toBeVisible()
  const card=page.locator('.market-app-card').first()
  const cardAppearance=()=>card.evaluate(element=>Object.fromEntries(['backgroundColor','backgroundImage','borderTopColor','color'].map(key=>[key,getComputedStyle(element)[key]]).concat(
    ['.market-app-title','.market-app-description','.market-app-meta','.market-app-tag','.market-app-price','.market-app-save'].map(selector=>[selector,getComputedStyle(element.querySelector(selector)).color])
  )))
  const darkAppearance=await cardAppearance()
  await page.evaluate(async()=>{const {applyTheme}=await import('/src/utils/theme.js');applyTheme('light')})
  await expect(card).toHaveCSS('background-color','rgb(255, 255, 255)')
  await expect(card.locator('.market-app-title')).toHaveCSS('color','rgb(36, 35, 51)')
  const lightAppearance=await cardAppearance()
  expect(lightAppearance.borderTopColor).toBe(darkAppearance.borderTopColor)
  expect(lightAppearance.color).not.toBe(darkAppearance.color)
  await page.screenshot({path:testInfo.outputPath('market-light-cards.png')})
  await page.evaluate(async()=>{const {applyTheme}=await import('/src/utils/theme.js');applyTheme('dark')})
  await page.screenshot({path:testInfo.outputPath('market-focused-layout.png')})
  if (!isMobile) {
    await page.getByRole('button',{name:'Collapse the side panel'}).click()
    await expect(page.locator('aside')).toHaveCSS('width','56px')
    await expect(page.getByRole('navigation',{name:'Business sections'}).getByRole('button',{name:'Marketplace',exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Expand the side panel'}).click()
    const frameBefore=await page.locator('[data-frame-nav]').boundingBox()
    const mainBefore=await page.locator('main').boundingBox()
    await page.getByRole('button',{name:'Developer',exact:true}).click()
    await expect(page.getByRole('banner',{name:'Developer header'})).toBeVisible()
    const developerFrame=await page.locator('[data-frame-nav]').boundingBox()
    expect({y:developerFrame.y,height:developerFrame.height}).toEqual({y:frameBefore.y,height:frameBefore.height})
    expect((await page.locator('main').boundingBox()).y).toBe(mainBefore.y)
    await page.getByRole('button',{name:'Business',exact:true}).click()
    await expect(page.getByRole('banner',{name:'Business header'})).toBeVisible()
    const businessFrame=await page.locator('[data-frame-nav]').boundingBox()
    expect({y:businessFrame.y,height:businessFrame.height}).toEqual({y:frameBefore.y,height:frameBefore.height})
    expect((await page.locator('main').boundingBox()).y).toBe(mainBefore.y)
  }
  if (isMobile) await page.getByRole('button',{name:'Toggle menu'}).click()
  await page.getByRole('button',{name:isMobile?'SETTINGS & TOOLS':'Workspace settings',exact:true}).click()
  await expect(page.getByRole('button',{name:'Integrations',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Integrations',exact:true}).click()
  await expect(page.getByRole('heading',{name:'integrations',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
