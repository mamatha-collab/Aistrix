import { test, expect } from '@playwright/test'

test('account and workspace menus dismiss outside and with Escape', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'The phone account menu has its own outside backdrop.')
  await page.goto('/e2e/fixtures/?scenario=shared-row')
  const account = page.getByRole('button', { name: 'Account menu', exact: true })
  await account.click()
  await expect(account).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('menu').getByText('fixture@example.invalid', { exact: true }).click()
  await expect(account).toHaveAttribute('aria-expanded', 'true')
  await page.locator('.developer-content').click({ position: { x: 20, y: 250 } })
  await expect(account).toHaveAttribute('aria-expanded', 'false')
  const workspace = page.locator('.developer-workspace-summary')
  await workspace.locator('summary').click()
  await expect(workspace).toHaveAttribute('open', '')
  await account.click()
  await expect(workspace).not.toHaveAttribute('open', '')
  await expect(account).toHaveAttribute('aria-expanded', 'true')
  await page.keyboard.press('Escape')
  await expect(account).toHaveAttribute('aria-expanded', 'false')
  await workspace.locator('summary').click()
  await page.locator('.developer-content').click({ position: { x: 20, y: 250 } })
  await expect(workspace).not.toHaveAttribute('open', '')
  await workspace.locator('summary').click()
  await page.keyboard.press('Escape')
  await expect(workspace).not.toHaveAttribute('open', '')
  await expect(page.locator('aside').getByRole('button', { name: 'Settings', exact: true })).toHaveCount(0)
})

test('purple light mode keeps all grouped Developer steps available', async ({ page }, testInfo) => {
  await page.goto('/e2e/fixtures/?scenario=shared-row')
  await page.evaluate(async () => {
    const { applyTheme } = await import('/src/utils/theme.js')
    applyTheme('light')
  })
  if (testInfo.project.name === 'mobile') {
    const nav = page.getByRole('navigation', { name: 'Developer mobile navigation' })
    await expect(nav.getByRole('button')).toHaveCount(4)
    await nav.getByRole('button', { name: 'Manage', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Revenue', exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('developer-purple-mobile.png') })
    return
  }
  const row = page.locator('[aria-label="Developer navigation"]')
  await expect(row.locator('[data-group]')).toHaveCount(3)
  await expect(row.locator('[data-group] button')).toHaveCount(10)
  const design = row.getByRole('button', { name: 'Design Blueprint' })
  await expect(design).toHaveAttribute('aria-current', 'step')
  await expect(design).toHaveCSS('background-color', 'rgb(238, 232, 248)')
  const header = page.getByRole('banner', { name: 'Developer header' })
  await expect(header).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(header.getByRole('button', { name: 'Runs', exact: true }).locator('svg')).toBeVisible()
  await expect(header.getByRole('button', { name: '+ App', exact: true })).toHaveCSS('color', 'rgb(255, 255, 255)')
  await row.locator('button[title="Revenue: Profit"]').click()
  await expect(page.getByRole('heading', { name: 'Revenue', exact: true })).toBeVisible()
  await design.click()
  await expect(design).toHaveAttribute('aria-current', 'step')
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.screenshot({ path: testInfo.outputPath('developer-purple-light.png') })
})

test('Developer second row spans sidebar and workspace', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'mobile', 'The shared desktop row becomes the mobile navigation.')
  await page.route('http://localhost:8000/**', route => route.abort())
  await page.goto('/e2e/fixtures/?scenario=shared-row&loading=1')
  const row = page.locator('[aria-label="Developer navigation"]')
  const header = page.getByRole('banner', { name: 'Developer header' })
  const initialHeader = await header.boundingBox()
  const initialRow = await row.boundingBox()
  await page.evaluate(() => window.dispatchEvent(new Event('fixture-ready')))
  await expect(row.getByRole('button', { name: 'Business', exact: true })).toBeVisible()
  await expect(header.getByRole('button', { name: 'Account menu' })).toBeVisible()
  expect(await header.boundingBox()).toEqual(initialHeader)
  expect(await row.boundingBox()).toEqual(initialRow)
  await expect(row.locator(':scope > [data-section]')).toHaveCount(3)
  await expect(row.locator('button[title="Revenue: Profit"]').filter({ visible: true })).toBeVisible()
  await row.locator('button[title="Revenue: Profit"]').filter({ visible: true }).click()
  await row.locator('button[title="Design: Blueprint"]').filter({ visible: true }).click()
  for (const width of [1440, 1920]) {
    await page.setViewportSize({ width, height: 1000 })
    const bounds = await row.boundingBox()
    expect(bounds.x).toBe(0)
    expect(bounds.width).toBe(width)
    const left = await row.locator(':scope > div').first().boundingBox()
    const content = await row.locator(':scope > div').last().boundingBox()
    expect(left.y).toBe(content.y)
    expect(left.height).toBe(content.height)
  }
  await page.screenshot({ path: testInfo.outputPath('shared-row.png') })
})

