import { test, expect } from '@playwright/test'
test.beforeEach(({ isMobile }) => { test.skip(!!isMobile, 'Prompt editing is a desktop workflow.') })
const improve = page => page.locator('button[title="Improve: Iterate"]').filter({ visible: true }).click()
test('candidate saves with a change reference and preserves the published prompt', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await improve(page)
  const prompt = page.getByLabel('Candidate system prompt')
  await expect(prompt).toHaveValue('Answer the task in markdown with a Summary section.')
  await expect(page.getByRole('button', { name: 'Save candidate and open Design' })).toBeDisabled()
  await prompt.fill('Never invent an invoice number. Ask for missing invoice details.')
  await page.getByRole('button', { name: 'Save candidate and open Design' }).click()
  await expect(page.getByText('Move back to Design?', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Move to Design', exact: true }).click()
  const saved = await page.evaluate(() => window.buildFixture.tables.apps[0])
  expect(saved.system_prompt).toContain('Never invent')
  expect(saved.change_note.improvement_id).toBeTruthy()
  expect(saved.change_note.note).toContain(saved.change_note.improvement_id)
  expect(saved.prod_snapshot.system_prompt).toBe('Answer the task in markdown with a Summary section.')
  expect(saved.is_published).toBe(true)
  await improve(page)
  await expect(prompt).toHaveValue(saved.system_prompt)
})
test('switching apps asks first, clears the unrelated candidate and offers it back on return', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await improve(page)
  await page.getByLabel('Candidate system prompt').fill('Unsaved candidate for invoice app')
  let asked = ''
  page.once('dialog', dialog => { asked = dialog.message(); dialog.accept() })
  await page.getByLabel('App to operate').selectOption('app-2')
  await expect(page.getByLabel('Candidate system prompt')).not.toHaveValue('Unsaved candidate for invoice app')
  expect(asked).toContain('Leave without saving your candidate prompt')
  await page.getByLabel('App to operate').selectOption('app-1')
  await expect(page.getByText(/Restore your unsaved candidate/)).toBeVisible()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await expect(page.getByLabel('Candidate system prompt')).toHaveValue('Unsaved candidate for invoice app')
})

test('an unsaved candidate survives a reload, and leaving asks first', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await improve(page)
  await page.getByLabel('Candidate system prompt').fill('Recover me after a crash.')
  await expect(page.getByText('Unsaved changes')).toBeVisible()
  page.once('dialog', dialog => dialog.accept())          // beforeunload on reload
  await page.reload()
  await improve(page)
  await expect(page.getByText(/Restore your unsaved candidate/)).toBeVisible()
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await expect(page.getByLabel('Candidate system prompt')).toHaveValue('Recover me after a crash.')
  page.once('dialog', dialog => dialog.dismiss())         // stay
  await page.locator('button[title="Monitor: Usage"]').filter({ visible: true }).click()
  await expect(page.getByLabel('Candidate system prompt')).toHaveValue('Recover me after a crash.')
  await page.getByRole('button', { name: 'Discard changes' }).click()
  await expect(page.getByLabel('Candidate system prompt')).toHaveValue('Answer the task in markdown with a Summary section.')
  expect(await page.evaluate(() => Object.keys(localStorage).some(k => k.startsWith('aistrix_draft:improve')))).toBe(false)
})

test("a teammate's newer prompt is never overwritten silently", async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await improve(page)
  await page.getByLabel('Candidate system prompt').fill('My candidate.')
  await page.evaluate(() => { window.buildFixture.tables.apps[0].system_prompt = "Teammate's newer prompt." })
  await page.getByRole('button', { name: 'Save candidate and open Design' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'changed since you started' })).toBeVisible()
  expect(await page.evaluate(() => window.buildFixture.tables.apps[0].system_prompt)).toBe("Teammate's newer prompt.")
  await page.getByRole('button', { name: 'Load the saved prompt' }).click()
  await expect(page.getByLabel('Candidate system prompt')).toHaveValue("Teammate's newer prompt.")
})

