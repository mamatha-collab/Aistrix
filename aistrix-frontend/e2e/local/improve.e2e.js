test('both versions answering the same input are saved to the comparison history', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await improve(page)
  await page.getByLabel('Candidate system prompt').fill('Ask for the missing invoice number.')
  await page.getByPlaceholder('Enter a test input to run against both versions…').fill('Check this invoice')
  await page.getByRole('button', { name: /Run v1/ }).click()
  await page.getByRole('button', { name: 'Run candidate', exact: false }).click()
  const history = page.getByRole('region', { name: 'Comparison history' })
  await expect(history.getByText(/vs Draft candidate/)).toBeVisible()
  const saved = await page.evaluate(() => window.buildFixture.tables.app_comparisons[0])
  expect(saved.input).toBe('Check this invoice')
  expect(saved.candidate.prompt).toBe('Ask for the missing invoice number.')
  expect(saved.baseline_output && saved.candidate_output).toBeTruthy()
  await history.getByText(/vs Draft candidate/).click()
  await history.getByRole('button', { name: 'Save input as a test' }).click()
  await history.getByLabel('Expected behavior').fill('invoice number')
  await history.getByRole('button', { name: 'Save test' }).click()
  await expect(history.getByText('Test saved. Run it in Build → Test.')).toBeVisible()
  expect(await page.evaluate(() => window.buildFixture.tables.app_test_cases.at(-1).input)).toBe('Check this invoice')
})

test('comparison uses the candidate and clears obsolete results when its input changes', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await improve(page)
  await page.getByLabel('Candidate system prompt').fill('Ask for the missing invoice number.')
  const input = page.getByPlaceholder('Enter a test input to run against both versions…')
  await input.fill('Check this invoice')
  await page.getByRole('button', { name: 'Run candidate', exact: false }).click()
  await expect(page.getByText(/Who will use it\?/).filter({ hasNot: page.locator('button') })).toBeVisible()
  expect(await page.evaluate(() => window.buildFixture.requests.filter(r => r.path === '/run').at(-1).body.system_prompt)).toBe('Ask for the missing invoice number.')
  await input.fill('Different evidence')
  await expect(page.getByText(/Who will use it\?/).filter({ hasNot: page.locator('button') })).toHaveCount(0)
})
