import { expect, test } from '@playwright/test'

test.beforeEach(({ isMobile }) => {
  test.skip(!!isMobile, 'Phones use the monitoring workspace (covered in mobile-developer).')
})

const tab = (page, title) => page.locator(`button[title="${title}"]`).filter({ visible: true }).click()

test('Monitor opens on All apps while Eval retains the relevant app', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=monitor')
  await tab(page, 'Evaluate: Quality')
  await page.getByLabel('App to operate').selectOption('app-2')
  await tab(page, 'Monitor: Usage')
  await expect(page.getByLabel('App to monitor')).toHaveValue('all')
  await page.getByLabel('App to monitor').selectOption('app-1')
  await tab(page, 'Evaluate: Quality')
  await expect(page.getByLabel('App to operate')).toHaveValue('app-1')
  await tab(page, 'Monitor: Usage')
  await expect(page.getByLabel('App to monitor')).toHaveValue('all')
  await page.getByLabel('App to monitor').selectOption('app-2')
  await tab(page, 'Monitor: Usage')
  await expect(page.getByLabel('App to monitor')).toHaveValue('all')
  await page.reload()
  await expect(page.getByLabel('App to monitor')).toHaveValue('all')
})

test('Monitor shows production health from the server with alerts, per-app detail and versions', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=monitor')
  await tab(page, 'Monitor: Usage')
  const attention = page.getByRole('region', { name: 'Needs attention' })
  await expect(attention).toContainText('Fixture Assistant: 40% of runs failed in the last 24 hours')
  await expect(page.getByRole('row', { name: /Fixture Assistant/ })).toContainText('needs attention')
  await expect(page.getByRole('row', { name: /Second Assistant/ })).toContainText('0')
  await expect(page.getByText(/your own draft and test runs aren't counted/i)).toBeVisible()

  await page.getByRole('row', { name: /Fixture Assistant/ }).getByRole('button', { name: 'Details →' }).click()
  await expect(page.getByLabel('App to monitor')).toHaveValue('app-1')
  await expect(page.getByText('Typical response')).toBeVisible()
  await expect(page.getByRole('row', { name: /v2\s*live/ })).toBeVisible()
  await expect(page.getByText('Timed out')).toBeVisible()
  await expect(page.getByText('Website visitors', { exact: true })).toBeVisible()

  await page.getByLabel('Period').selectOption('30')
  await expect.poll(() => page.evaluate(() => window.buildFixture.requests.some(r => r.path === '/v1/apps/app-1/monitor'))).toBe(true)
  await expect(page.getByRole('img', { name: /last 30 days/ })).toBeVisible()
})

test('Monitor errors are shown with a retry, never as zero traffic', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=monitor')
  await page.evaluate(() => { window.buildFixture.failures['/v1/monitor'] = 'Monitoring is temporarily unavailable' })
  await tab(page, 'Monitor: Usage')
  await expect(page.getByRole('alert')).toContainText('Monitoring is temporarily unavailable')
  await expect(page.getByRole('table')).toHaveCount(0)
  await page.evaluate(() => { delete window.buildFixture.failures['/v1/monitor'] })
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByRole('row', { name: /Fixture Assistant/ })).toBeVisible()
})

test('automatic refresh pauses when hidden and failed refresh retains marked-stale data', async ({ page }) => {
  await page.clock.install()
  await page.goto('/e2e/fixtures/?scenario=monitor')
  await tab(page, 'Monitor: Usage')
  await expect(page.getByText(/Updated /)).toBeVisible()
  const requests = () => page.evaluate(() => window.buildFixture.requests.filter(r => r.path === '/v1/monitor').length)
  const first = await requests()
  await page.clock.fastForward(60000)
  await expect.poll(requests).toBe(first + 1)
  await page.evaluate(() => { Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' }); document.dispatchEvent(new Event('visibilitychange')) })
  await page.clock.fastForward(120000)
  expect(await requests()).toBe(first + 1)
  await page.evaluate(() => { window.buildFixture.failures['/v1/monitor'] = 'Refresh interrupted'; Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'visible' }); document.dispatchEvent(new Event('visibilitychange')) })
  await expect(page.getByRole('alert').filter({ hasText: 'Refresh interrupted' })).toBeVisible()
  await expect(page.getByText(/Showing the last successful update/)).toBeVisible()
  await expect(page.getByRole('row', { name: /Fixture Assistant/ })).toBeVisible()
  await page.evaluate(() => { delete window.buildFixture.failures['/v1/monitor'] })
  await page.getByRole('button', { name: 'Try again' }).click()
  await expect(page.getByText('Refresh interrupted')).toHaveCount(0)
})

test('new scope never displays the previous period and alerts lead to app diagnostics', async ({ page }, testInfo) => {
  await page.goto('/e2e/fixtures/?scenario=monitor')
  await tab(page, 'Monitor: Usage')
  await page.getByRole('button', { name: 'Inspect app →' }).click()
  await expect(page.getByLabel('App to monitor')).toHaveValue('app-1')
  await expect(page.getByText('Why runs failed', { exact: true })).toBeVisible()
  await page.getByLabel('App to monitor').selectOption('app-2')
  await expect(page.getByText('Timed out', { exact: true })).toHaveCount(0)
  await expect(page.getByText(/No runs in this period/)).toBeVisible()
  await page.getByLabel('App to monitor').selectOption('all')
  await page.screenshot({ path: testInfo.outputPath('monitor-overview.png') })
})

test('Free developers see Basic analytics, with the rest labelled as Verified-only', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=monitor')
  await page.evaluate(() => { window.buildFixture.analytics = 'basic' })
  await tab(page, 'Monitor: Usage')
  await page.getByLabel('App to monitor').selectOption('app-1')
  await expect(page.getByText('Typical response')).toBeVisible()
  await expect(page.getByText('Included for Verified developers').first()).toBeVisible()
  await expect(page.getByText('No response timings recorded')).toHaveCount(0)
  await expect(page.getByText(/Alerts .* are included for Verified developers/)).toBeVisible()
  await expect(page.getByText('No alert thresholds reached in this period.', { exact: false })).toHaveCount(0)
  await expect(page.getByText(/Per-version health is included for Verified developers/)).toBeVisible()
  await expect(page.getByRole('row', { name: /v2\s*live/ })).toHaveCount(0)
})
