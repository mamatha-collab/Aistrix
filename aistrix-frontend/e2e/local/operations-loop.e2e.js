import { test, expect } from '@playwright/test'

test.beforeEach(({ isMobile }) => {
  test.skip(!!isMobile, 'Phones use the monitoring workspace; Build and regression authoring are tested on desktop.')
})

const workflow = page => page.getByRole('region', { name: 'Operate and Grow workflow' })
const tab = (page, title) => page.locator(`button[title="${title}"]`).filter({ visible: true }).click()

test('feedback flows into a regression and draft without changing the live app', async ({ page }, testInfo) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await tab(page, 'Evaluate: Quality')
  const flow = workflow(page)
  const list = flow.getByLabel('Feedback list')
  await expect(list.getByText('The answer invented an invoice number.', { exact: true })).toBeVisible()
  await expect(flow.getByText('The translation ignored the glossary.', { exact: true })).toHaveCount(0)
  await expect(list.getByRole('button')).toContainText(['New'])
  await list.getByRole('button').first().click()
  await expect(flow.getByLabel('Regression input')).toHaveValue('Check invoice with no invoice number.')   // the customer shared their question
  await expect(flow.getByRole('button', { name: 'Save regression test' })).toBeDisabled()
  await flow.getByLabel('Expected behavior').fill('Missing invoice number')
  await page.screenshot({ path: testInfo.outputPath('evaluate-feedback.png') })
  await page.evaluate(() => { window.buildFixture.failures['app_test_cases:insert'] = 'Storage temporarily unavailable' })
  await flow.getByRole('button', { name: 'Save regression test' }).click()
  await expect(page.getByText(/Could not save regression test: Storage temporarily unavailable/)).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.buildFixture.tables.app_test_cases.length)).toBe(0)
  await page.evaluate(() => { delete window.buildFixture.failures['app_test_cases:insert'] })
  await flow.getByRole('button', { name: 'Save regression test' }).click()
  await expect(flow.getByText(/Regression test saved. Run and edit it/)).toBeVisible()
  const saved = await page.evaluate(() => window.buildFixture.tables.app_test_cases[0])
  expect(saved.rules).toEqual([{ type: 'must-contain', value: 'Missing invoice number' }])
  // The feedback is linked to the test and moves to "investigating" (never "fixed" just for saving a test).
  await expect.poll(() => page.evaluate(() => window.buildFixture.feedback[0])).toMatchObject({ status: 'investigating', test_case_id: saved.id })
  await expect(list.getByRole('button').first()).toContainText('Investigating')

  await flow.getByRole('button', { name: 'Continue to Improve' }).click()
  await flow.getByRole('button', { name: 'Open draft fix in Design' }).click()
  await expect(page.getByText('Move back to Design?', { exact: true })).toBeVisible()
  await expect(page.getByPlaceholder('e.g. Replies are too long. Shorten them and always include the order number.')).toHaveValue(/run-invoice/)
  await page.getByRole('button', { name: 'Move to Design', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.buildFixture.tables.app_blueprints[0].blueprint.dev_phase)).toBe('design')
  const current = await page.evaluate(() => window.buildFixture.tables.apps[0])
  expect(current.is_published).toBe(true)
  expect(current.live_version).toBe(1)
  expect(current.prod_snapshot.system_prompt).toBe('Answer the task in markdown with a Summary section.')
  expect(current.change_note.note).toContain(saved.id)
  await tab(page, 'Evaluate: Quality')
  await expect(workflow(page).getByText(/Regression test saved. Run and edit it/)).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.buildFixture.tables.app_test_cases.length)).toBe(1)
  await workflow(page).getByRole('button', { name: 'Validate in Test' }).click()
  await expect(page.getByRole('heading', { name: 'Feedback regression coverage' })).toBeVisible()
  await page.getByRole('button', { name: /Run tests/, exact: false }).first().click()
  await expect.poll(() => page.evaluate(id => window.buildFixture.testRuns.some(r => r.case_ref === id), saved.id)).toBe(true)
  await page.getByRole('button', { name: 'Continue to Deploy →', exact: true }).click()
  await page.getByRole('button', { name: 'Monitor this app →', exact: true }).click()
  await expect(page.getByLabel('App to monitor')).toHaveValue('app-1')

  // Once the fix is live and healthy, the developer verifies it; it leaves the open list.
  await tab(page, 'Evaluate: Quality')
  await workflow(page).getByLabel('Feedback status').selectOption('verified')
  await expect.poll(() => page.evaluate(() => window.buildFixture.feedback[0].status)).toBe('verified')
  await workflow(page).getByRole('button', { name: 'Refresh feedback' }).click()
  await expect(workflow(page).getByText(/No open feedback/)).toBeVisible()
  await workflow(page).getByLabel('Feedback to show').selectOption('verified')
  await expect(workflow(page).getByLabel('Feedback list')).toContainText('The answer invented an invoice number.')
  await page.screenshot({ path: testInfo.outputPath('feedback-regression.png') })
})

test('app selection and feedback errors do not mix apps', async ({ page }) => {
  await page.goto('/e2e/fixtures/?scenario=operations')
  await tab(page, 'Evaluate: Quality')
  await workflow(page).getByLabel('App to operate').selectOption('app-2')
  await expect(workflow(page).getByText('The translation ignored the glossary.', { exact: true })).toBeVisible()
  await expect(workflow(page).getByLabel('Regression input')).toHaveValue('Translate the receipt.')
  await workflow(page).getByLabel('App to operate').selectOption('app-1')
  await expect(workflow(page).getByLabel('Regression input')).toHaveValue('Check invoice with no invoice number.')
  await page.evaluate(() => { window.buildFixture.failures['/v1/apps/app-1/feedback'] = 'Feedback unavailable' })
  await workflow(page).getByRole('button', { name: 'Refresh feedback' }).click()
  await expect(workflow(page).getByRole('alert')).toContainText('Feedback unavailable')
  await expect(workflow(page).getByText('The translation ignored the glossary.', { exact: true })).toHaveCount(0)
  await page.evaluate(() => { delete window.buildFixture.failures['/v1/apps/app-1/feedback'] })
  await workflow(page).getByRole('button', { name: 'Try again' }).click()
  await expect(workflow(page).getByRole('alert')).toHaveCount(0)
  await expect(workflow(page).getByLabel('Regression input')).toHaveValue('Check invoice with no invoice number.')
})
